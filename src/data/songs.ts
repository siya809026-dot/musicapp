export const getSongsByMood = (mood: string): Song[] => {
  return songs.filter((song) => song.mood.includes(mood));
};

export const getSongsByGenre = (genre: string): Song[] => {
  return songs.filter((song) => song.genre === genre);
};

export const searchSongs = (query: string): Song[] => {
  const lower = query.toLowerCase();
  return songs.filter(
    (song) =>
      song.title.toLowerCase().includes(lower) ||
      song.artist.toLowerCase().includes(lower) ||
      song.album.toLowerCase().includes(lower)
  );
};
